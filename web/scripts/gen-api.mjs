// Generate TypeScript types for the ARIA API from its OpenAPI schema.
//
//   pnpm gen:api            types from ../docs/openapi.json
//   pnpm gen:api --refresh  first re-export the schema from the Python app (needs uv)
//
// CI runs both and fails if either file changes, so the web client cannot drift from the API.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../..");
const schemaPath = resolve(repo, "docs/openapi.json");
const outPath = resolve(here, "../src/lib/api/schema.ts");

if (process.argv.includes("--refresh")) {
  execFileSync("uv", ["run", "aria", "openapi", "--out", schemaPath], {
    cwd: repo,
    stdio: "inherit",
    env: { ...process.env, ARIA_ENV: process.env.ARIA_ENV ?? "test" },
  });
}

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
// Fields with defaults stay optional: request bodies may omit them (the API fills them in).
const ast = await openapiTS(schema, {
  exportType: true,
  alphabetize: true,
  defaultNonNullable: false,
});
const header =
  "// Generated by scripts/gen-api.mjs from docs/openapi.json. Do not edit by hand.\n" +
  "/* eslint-disable */\n\n";
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, header + astToString(ast));
console.log(`wrote ${outPath}`);
